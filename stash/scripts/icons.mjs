// Writes every brand asset from scripts/brand-paths.mjs:
//   public/icons/icon.svg, maskable.svg + icon-192/512.png, maskable-512.png
//   public/brand/mark.svg, lockup-light.svg, lockup-dark.svg, lockup.png (for docs)
//   public/favicon.ico (16, 32, 48)
//   android/app/src/main/res/drawable/{ic_launcher_foreground,ic_launcher_background,splash,ic_notification}.xml
// Run with `npm run icons` after changing the paths.
import sharp from "sharp";
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { COLORS, MARK_CARDS, WORDMARK } from "./brand-paths.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const icons = root + "public/icons/";
const brand = root + "public/brand/";
const drawable = root + "android/app/src/main/res/drawable/";
mkdirSync(brand, { recursive: true });

const cards = (fill, { solid = false, transform = "" } = {}) =>
  `<g fill="${fill}"${transform ? ` transform="${transform}"` : ""}>${MARK_CARDS.map(
    (c) => `<path${solid || c.opacity === 1 ? "" : ` opacity="${c.opacity}"`} d="${c.d}"/>`,
  ).join("")}</g>`;

const svg = (viewBox, body) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${body}</svg>\n`;

// App icon ("any"): the mark on a rounded deep-ink tile.
const iconSvg = svg("0 0 108 108", `<rect width="108" height="108" rx="26" fill="${COLORS.ink}"/>${cards(COLORS.lime)}`);
// Maskable: full-bleed ink, mark scaled into the 80% safe circle.
const maskableSvg = svg("0 0 108 108", `<rect width="108" height="108" fill="${COLORS.ink}"/>${cards(COLORS.lime, { transform: "translate(54 54) scale(0.86) translate(-54 -54)" })}`);
// The bare mark, tight box, for places that draw their own background.
const markSvg = svg("25 21 58 66.5", cards(COLORS.lime));

// Lockup: icon tile + wordmark, text in ink (light backgrounds) or paper (dark backgrounds).
const TILE = 72;
const GAP = 18;
const TEXT_H = 50;
const k = TEXT_H / WORDMARK.height;
const lockupW = Math.ceil(TILE + GAP + WORDMARK.width * k);
const lockup = (text) =>
  svg(
    `0 0 ${lockupW} ${TILE}`,
    `<g transform="scale(${TILE / 108})"><rect width="108" height="108" rx="26" fill="${COLORS.ink}"/>${cards(COLORS.lime)}</g>` +
      `<path fill="${text}" transform="translate(${TILE + GAP} ${(TILE - TEXT_H) / 2 + 1}) scale(${k.toFixed(4)})" d="${WORDMARK.d}"/>`,
  );

writeFileSync(icons + "icon.svg", iconSvg);
writeFileSync(icons + "maskable.svg", maskableSvg);
writeFileSync(brand + "mark.svg", markSvg);
writeFileSync(brand + "lockup-light.svg", lockup(COLORS.ink));
writeFileSync(brand + "lockup-dark.svg", lockup(COLORS.paper));
console.log("svg: icon, maskable, mark, lockup-light, lockup-dark");

const png = (src, size) => sharp(Buffer.from(src), { density: 600 }).resize(size, size).png().toBuffer();
for (const [src, out, size] of [
  [iconSvg, "icon-192.png", 192],
  [iconSvg, "icon-512.png", 512],
  [maskableSvg, "maskable-512.png", 512],
]) {
  writeFileSync(icons + out, await png(src, size));
  console.log(`${out} (${size}px)`);
}

// favicon.ico with PNG entries (supported by every current browser).
const sizes = [16, 32, 48];
const images = await Promise.all(sizes.map((s) => png(iconSvg, s)));
const header = Buffer.alloc(6 + 16 * sizes.length);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
sizes.forEach((s, i) => {
  const e = 6 + 16 * i;
  header.writeUInt8(s, e);
  header.writeUInt8(s, e + 1);
  header.writeUInt16LE(1, e + 4);
  header.writeUInt16LE(32, e + 6);
  header.writeUInt32LE(images[i].length, e + 8);
  header.writeUInt32LE(offset, e + 12);
  offset += images[i].length;
});
writeFileSync(root + "public/favicon.ico", Buffer.concat([header, ...images]));
console.log("favicon.ico (16, 32, 48)");

// Android vector drawables (minSdk 26: the adaptive icon covers every launcher, no PNG mipmaps).
const vector = (w, h, vw, vh, body, comment) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${comment} Generated by scripts/icons.mjs; edit scripts/brand-paths.mjs instead. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${w}dp"
    android:height="${h}dp"
    android:viewportWidth="${vw}"
    android:viewportHeight="${vh}">
${body}</vector>
`;
const androidCards = (color, solid = false) =>
  MARK_CARDS.map(
    (c) => `    <path
        android:fillColor="${color.toUpperCase()}"${solid || c.opacity === 1 ? "" : `\n        android:fillAlpha="${c.opacity}"`}
        android:pathData="${c.d}" />
`,
  ).join("");

writeFileSync(
  drawable + "ic_launcher_foreground.xml",
  vector(108, 108, 108, 108, androidCards(COLORS.lime), 'The Stash mark: a rounded "S" of three stacked cards, inside the adaptive icon safe zone (21..87).'),
);
writeFileSync(
  drawable + "ic_launcher_background.xml",
  vector(108, 108, 108, 108, `    <path
        android:fillColor="${COLORS.ink.toUpperCase()}"
        android:pathData="M0,0h108v108h-108z" />
`, "Deep ink behind the mark."),
);
writeFileSync(
  drawable + "splash.xml",
  vector(160, 160, 108, 108, androidCards(COLORS.lime), "The Stash mark on the deep-ink splash while the site loads."),
);
// Status bar icon: white silhouette, cropped to the mark so it fills the 24dp box.
writeFileSync(
  drawable + "ic_notification.xml",
  vector(24, 24, 72, 72, `    <group android:translateX="-18" android:translateY="-18">
${androidCards("#FFFFFF", true).replace(/^/gm, "    ")}    </group>
`, "Status bar icon: the Stash mark, white on transparent, as Android requires."),
);
console.log("android: ic_launcher_foreground, ic_launcher_background, splash, ic_notification");
